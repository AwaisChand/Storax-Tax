  static String normalize(String? raw) {
    final code = (raw ?? '').trim().toUpperCase();
    if (isoCodes.contains(code)) return code;
    return 'US';
  }

  static String fromDeviceLocale() {
    return normalize(PlatformDispatcher.instance.locale.countryCode);
  }

  /// Physical location ISO code (e.g. PK), not the phone language region.
  static Future<String> fromCurrentLocation() async {
    try {
      final serviceEnabled = await Geolocator.isLocationServiceEnabled();
      if (!serviceEnabled) return fromDeviceLocale();

      var permission = await Geolocator.checkPermission();
      if (permission == LocationPermission.denied) {
        permission = await Geolocator.requestPermission();
      }
      if (permission == LocationPermission.denied ||
          permission == LocationPermission.deniedForever) {
        return fromDeviceLocale();
      }

      var position = await Geolocator.getLastKnownPosition();
      position ??= await Geolocator.getCurrentPosition(
        locationSettings: const LocationSettings(
          accuracy: LocationAccuracy.low,
        ),
      );

      final placemarks = await placemarkFromCoordinates(
        position.latitude,
        position.longitude,
      );
      if (placemarks.isEmpty) return fromDeviceLocale();
      return normalize(placemarks.first.isoCountryCode);
    } catch (_) {
      return fromDeviceLocale();
    }
  }
}
